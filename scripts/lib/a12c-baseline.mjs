// 🔴 이 파일이 없으면 래칫은 **아무것도 못 막는다.**
// ══════════════════════════════════════════════════════════════════════════════
//   래칫(ratchet)은 「지금보다 나빠지는 것」을 막는 장치다. 「지금」이 어디인지 적힌 것이
//   없으면 비교할 대상이 없고, 게이트는 무엇이 줄었는지 영원히 모른다.
//   그래서 수를 **여기 박아 둔다.**
//
//   🔴 왜 별도 모듈인가 — `scripts/lib/bundle-budget.mjs` 와 같은 이유다.
//      이 수는 게이트 본체(`check-a12c.mjs`)와 그 형제 픽스처(`check-a12c.selftest.mjs`)
//      **양쪽이 알아야 한다.** 두 곳에 리터럴로 박으면 한쪽만 고쳐지고 픽스처가 조용히
//      무의미해진다. `check-a12c.mjs` 는 최상위에서 실행하고 `process.exit` 까지 하는
//      **실행 스크립트**라 import 하는 순간 게이트가 돌아 버린다.
//      그래서 정본을 부작용 없는 이 모듈에 둔다.
//
// ══════════════════════════════════════════════════════════════════════════════
// 🔴 이 수를 **올리는 것만** 허용된다. 내리는 것은 완화다.
// ══════════════════════════════════════════════════════════════════════════════
//   · 조작가능 수가 늘었으면 이 파일을 그 값으로 **올려라.** 그것이 래칫을 조이는 행위다.
//   · 값이 줄어서 게이트가 빨간불이면 **이 파일을 내려서 통과시키지 마라.** 배선을 고쳐라.
//     이 파일을 내리는 것은 D-041(완화로 통과시키지 않는다) 위반이다.
//   · 재생성 스크립트(`--write-baseline` 같은 버튼)를 **일부러 만들지 않았다.**
//     손으로 고치게 두는 것이 「무심코 재기준선을 눌러 회귀를 지운다」를 막는 유일한 장치다.
//
// ══════════════════════════════════════════════════════════════════════════════
// 🔴 이 래칫이 **못 막는 것** — PLN 이 지목한 이 안의 유일한 약점
// ══════════════════════════════════════════════════════════════════════════════
//   `wafer` · `etch` 는 기준선이 **0** 이다. 0 아래로는 내려갈 수 없으므로
//   **이 두 공정에서 래칫은 아무것도 막지 못한다.** 「0을 유지하는 것」이 래칫상으로는
//   합격이다. 그것은 합격이 아니라 **미착수**다.
//   → 게이트는 매 실행마다 이 사실을 명시한다(출력의 「기준선 0 = 미착수」 절).
//     이 두 공정은 래칫이 아니라 **L2 커버리지 100 %** 조건이 잡는다.
//
// ══════════════════════════════════════════════════════════════════════════════
// 실측 출처
