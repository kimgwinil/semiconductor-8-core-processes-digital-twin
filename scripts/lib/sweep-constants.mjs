/* ══════════════ 🔴 여기에 두지 **않은** 것 — 「랩당 표본 수」 ══════════════
 *
 * `check-passwindow.mjs` 의 `SAMPLES_PER_LAB = 4000` 과
 * `lib/live-judgment.mjs` 의 `LIVE_JUDGMENT_SAMPLES_PER_LAB = 3000` 은
 * **이름이 같았을 뿐 같은 개념이 아니다.** 통일하지 않고 이름을 갈랐다.
 *
 *   · `check-passwindow` 4000 = **희귀 위반을 찾는 탐색 예산**이다.
 *     「물리적으로 불가능한 값이 합격으로 계상되는 조합」이 있는지 뒤진다 —
 *     못 찾으면 통과이므로, 표본이 줄면 **게이트가 조용히 둔해진다.**
 *
 *   · `check-live-judgment` 3000 = **합격·불합격이 둘 다 나오는지 보는 관측 예산**이다.
 *     못 찾으면 통과가 아니라 `UNDETERMINED`(종료코드 4)로 **판정을 보류한다.**
 *     표본이 줄어도 둔해지지 않고 「모른다」가 늘 뿐이다.
 *
 * 🔴 실측 근거(2026-08-21): 표본을 3,000 → 3,000,000 으로 1000배 늘려도
 *    `check-live-judgment` 의 판정은 바뀌지 않았다(`eds/lab-applied` 여전히 UNDETERMINED).
 *    즉 이 수는 **판정을 가르는 임계가 아니라 운영 예산**이다. 반면 `check-passwindow` 의 4000 은
 *    줄이면 탐지력이 직접 깎인다. 한 수로 묶으면 한쪽을 조정할 때 **다른 쪽 민감도가 딸려 움직인다.**
 *
 * 🔴 그래서 `check-passwindow.mjs` 의 4000 은 **건드리지 않았다.**
 */
