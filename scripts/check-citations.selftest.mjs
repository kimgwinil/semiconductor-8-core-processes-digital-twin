#!/usr/bin/env node
/**
 * check-citations 자체 검증 픽스처.
 *
 * 🔴 **왜 필요한가.** 게이트가 「통과」했을 때 그것이 *위반이 없어서*인지 *못 봐서*인지는
 *    픽스처 없이는 증명되지 않는다. **합격만 나오는 게이트도 위반이고 불합격만 나오는 게이트도 위반**이다(R-7c).
 *    그래서 아래는 **통과해야 하는 픽스처와 실패해야 하는 픽스처를 둘 다** 갖는다.
 *
 * 🔴 **주입은 `src/` 밖에서 한다.** 다른 담당이 `src/` 를 동시 편집 중이라 위반 코드를 `src/` 에 넣으면
 *    그쪽 게이트 측정을 오염시킨다(2026-08-21 실측 사고).
 *    다만 `check-guard-naming.selftest.mjs` 와 달리 **tmpdir 이 아니라 저장소 안**
 *    `scripts/fixtures/citations/**` 에 둔다. 사유:
 *      · 핵심 픽스처(ⓐ)는 **진짜 `03_실습3단계명세.md`** 를 상대로 돌려야 증명이 된다.
 *        가짜 명세를 만들면 「폐기 배너가 폐기 문구를 다시 적는다」는 실물 함정이 재현되지 않는다.
 *      · 픽스처 본문 자체가 **왜 그렇게 판정돼야 하는지의 근거 문서**다. 사람이 열어 볼 수 있어야 한다.
 *      · `scripts/fixtures/` 는 `check-gate-registration` 의 스캔 대상이 아니고(하위 디렉터리),
 *        `tsconfig.json` 의 `include` 도 `["src","tests","vite.config.ts"]` 라 `tsc` 가 보지 않는다.
 *
 * 사용: node scripts/check-citations.selftest.mjs
 * 종료코드: 0 전건 통과 · 1 픽스처 실패
 */
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const GATE = path.join(HERE, 'check-citations.mjs');
const FX = path.join(HERE, 'fixtures', 'citations');

function run(args) {
  try {
    const out = execFileSync('node', [GATE, ...args], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
    return { code: 0, out };
  } catch (e) { return { code: e.status ?? -1, out: (e.stdout ?? '') + (e.stderr ?? '') }; }
}
const onSrc = (name, ...extra) => run(['--src', path.join(FX, name), ...extra]);

const CASES = [];
/** expect: 기대 종료코드(0 통과 · 1 판정 실패 · 2 계측기 고장) · assert: 출력이 무엇을 말해야 하는가 */
const add = (id, desc, expect, fn, assert) => CASES.push({ id, desc, expect, fn, assert });

/* ══════════════════════════════════════════════════════════════════════════════
 * ⓐ 🔴🔴 **이 게이트의 핵심 수용기준(AC-R4).**
 *    「처음 20 nm 구간에서는 직선」은 진짜 `03` 안에 **물리적으로 존재**한다(L741).
 *    그러나 존재하는 곳이 **삭제 선언 배너 안뿐**이라 실패로 잡혀야 한다.
 *    🔴 이 픽스처가 통과로 뒤집히면 게이트가 R-4 를 잃은 것이다.
 * ══════════════════════════════════════════════════════════════════════════════ */
add('ⓐ', '폐기 배너 안에만 있는 문구를 인용 → 실패 + 「폐기 영역 안에만 있다」로 사유를 밝힌다', 1,
  () => onSrc('dead'),
  (o) => /폐기 영역 안에만 있다/.test(o) && /배제영역 1곳 @L741/.test(o)
    ? null : '「폐기 영역 안에만 있다 (배제영역 @L741)」 진단이 출력되지 않았다');

/* ⓑ 반대 방향 — `>` 블록 안의 **살아 있는 정본**을 인용하면 통과해야 한다.
 *    `>` 를 통째로 배제하는 구현은 여기서 거짓 실패한다. */
add('ⓑ', '살아 있는 `>` 블록(03:546–559)의 문구를 인용 → 통과', 0,
  () => onSrc('live'),
  (o) => /확정통과 2/.test(o) ? null : '확정 통과 2건이 나오지 않았다(배제 규칙이 너무 넓다)');

/* ⓒ AC-R1 — 학습자용 UI 문구·표지 없는 「」를 인용으로 오검출하지 않는다. */
add('ⓒ', '문자열 리터럴·표지 없는 「」·다른 문서 인용 → 검사 인용 0건(오검출 없음)', 0,
  () => onSrc('noise'),
  (o) => /검사한 인용 0 건/.test(o) && /형태가 아니어서 검사하지 않은 「」 4 건/.test(o)
    ? null : '오검출 0건 + 사각지대 4건 전건 나열이 확인되지 않았다');

/* ⓓ AC-R2 — 「2건 이상 = 경고」. 실패로 만들면 게이트를 첫날부터 못 쓴다.
 *    🔴 **2026-08-22 재동기: 「2곳 @L134,557」 → 「3곳 @L137,148,571」.**
 *    다른 5곳(ⓐⓔⓛⓞⓟ)은 정본 앞머리가 늘어 **전부 정확히 +14** 밀린 순수 행번호 밀림이지만,
 *    **ⓓ 만은 건수가 2→3 으로 늘었다. 기대를 실측에 맞춘 것이 아니다.**
 *    구 L134→L148(항목 4), 구 L557→L571 은 +14 밀림 그대로이고,
 *    **늘어난 L137 은 PLN 이 2026-08-22 12:48 에 `03` §「판정 출력의 합격 조건」 판정표에 새로 넣은
 *    「양측 창」 행**이며 그 칸 안에 「판정은 이 차트에서 한다」가 **실재**한다(직접 확인).
 *    즉 명세에 그 문구가 **한 곳 더 생긴 것**이므로 「모호 3곳」이 옳은 기대값이다.
 *    🔴 정본에서 그 표 행이 사라지면 이 픽스처는 다시 2곳으로 돌아가야 한다 — 그때 고칠 자리가 여기다. */
add('ⓓ', '명세 본문 2곳에 있는 문구 → 통과하되 「모호」 경고', 0,
  () => onSrc('ambiguous'),
  (o) => /모호 3곳 @L137,148,571/.test(o) && /경고 1/.test(o) ? null : '모호 경고가 나오지 않았다');

/* ⓔ 생략부호 분할 — 앞 조각은 살아 있고 뒤 조각이 죽었으면 실패하되, **앞 조각이 살아 있다는 사실도 출력**해야 한다. */
add('ⓔ', '`…` 로 나뉜 인용은 조각마다 대조 — 앞 살아 있음 + 뒤 죽음 → 실패', 1,
  () => onSrc('ellipsis'),
  (o) => /유일 1곳 @L620/.test(o) && /명세에 없다/.test(o) ? null : '조각별 판정이 따로 출력되지 않았다');

/* ⓕ 중첩 인용 — 첫 `」` 에서 끊으면 인용문이 잘린다. */
add('ⓕ', '인용문 안에 또 「」가 있는 경우 깊이 짝짓기로 통째 추출', 1,
  () => onSrc('nested'),
  (o) => /중첩 인용 포함/.test(o) && /캡션이 붙는다|선형 → 포물/.test(o) ? null : '중첩 인용이 통째로 추출되지 않았다');

/* ⓖ R-5 래칫(악화 금지) — 기준선을 넘으면 실패. */
add('ⓖ', 'R-5 행번호 인용이 기준선을 넘으면 실패(악화 금지 래칫)', 1,
  () => onSrc('lineref', '--r5-baseline', '2'),
  (o) => /기준선 2 건을 넘었다/.test(o) ? null : '래칫 사유가 출력되지 않았다');

/* ⓗ 같은 파일이 기준선 안에서는 **경고에 그친다** — 래칫이 「항상 실패」가 아님을 증명한다. */
add('ⓗ', '같은 R-5 픽스처가 기준선 안이면 경고에 그친다(불합격만 나오는 게이트도 위반이다)', 0,
  () => onSrc('lineref', '--r5-baseline', '99'),
  (o) => /R-5 · 행번호 인용 금지 패턴 — ⚠️/.test(o) ? null : 'R-5 가 경고로 남지 않았다');

/* ⓘ 🔴 R-7d — **계측기 고장(2)을 판정 실패(1)로 위장하지 않는다.** */
add('ⓘ', '명세 파일이 없으면 종료코드 2(계측기 고장) — 1 로 위장하지 않는다', 2,
  () => run(['--spec', '/nonexistent/__no_such_spec__.md']),
  (o) => /재지 못한 것입니다\(종료코드 2\)/.test(o) ? null : '계측기 고장 문구가 없다');

add('ⓙ', '소스 디렉터리가 없으면 종료코드 2', 2,
  () => run(['--src', '/nonexistent/__no_such_src__']),
  (o) => /재지 못한 것입니다\(종료코드 2\)/.test(o) ? null : '계측기 고장 문구가 없다');

/* ⓚ 🔴 R-6 은 **실패로 세우지 않는다** — 표제 서식이 통일되기 전엔 대조 기준 자체가 없다.
 *    승격 문구가 출력에 남아 있는지까지 본다(AC-R6). */
add('ⓚ', 'R-6 은 경고만이며 승격 문구가 출력에 포함된다(AC-R6)', 0,
  () => onSrc('live'),
  (o) => /표제 서식 통일\(§재개-L4\) 완료 후 R-6 을 실패로 승격한다/.test(o)
    ? null : 'AC-R6 이 요구한 승격 문구가 출력에 없다');

/* ⓛ AC-R4b — 배제한 영역을 **행 범위와 사유까지** 낸다. 조용히 뺀 것이 없어야 한다. */
add('ⓛ', 'AC-R4b: 배제 영역의 행 범위·단위·표지·머리행을 전부 출력한다', 0,
  () => onSrc('live'),
  (o) => /배제 영역 \d+ 개 · 배제 행 \d+/.test(o) && /L741–747 \[S3 블록\(머리행이 배너 선언\)\] \[삭제했다/.test(o)
    ? null : '배제 영역 목록이 행 범위·배제 단위·표지와 함께 출력되지 않았다');

/* ══════════════════════════════════════════════════════════════════════════════
 * R-4 v2 정밀화 (2026-08-22 후속) — 🔴 **양방향을 둘 다 고정하기 전에는 적용하지 않는다**
 *   ⓝ 좁힌 쪽이 실제로 검사되는가   ⓞⓟ 진짜 폐기는 여전히 배제되는가(행·절)
 * ══════════════════════════════════════════════════════════════════════════════ */
add('ⓝ', '🔴 살아 있는 블록(03:2647–2688)이 표 한 칸의 「폐기」로 죽지 않는다 — 참뜻의 자리로 통과', 0,
  () => onSrc('revived'),
  (o) => /확정통과 2/.test(o) ? null : '배제가 여전히 블록 단위다 — 살아 있는 정본이 검사되지 않는다');

add('ⓞ', '🔴 같은 블록 안의 폐기 **표 행**(03:2678)은 여전히 배제된다 — 좁히다 R-4 를 잃지 않았다', 1,
  () => onSrc('deprow'),
  (o) => /폐기 영역 안에만 있다/.test(o) && /배제영역 1곳 @L2678/.test(o)
    ? null : 'S1 행 배제가 동작하지 않았다 — 좁히다가 R-4 본래 기능을 깨뜨렸다');

add('ⓟ', '🔴 표제(`### 아직 보류인 것`)가 지배하는 절 전체가 배제된다(S2)', 1,
  () => onSrc('depsection'),
  (o) => /폐기 영역 안에만 있다/.test(o) && /배제영역 1곳 @L3066/.test(o)
    ? null : 'S2 표제 지배가 동작하지 않았다');

/* ⓠ 🔴🔴 **「조용히 검사에서 빠지는 것」** — 이 저장소가 하루 종일 쫓은 그 병.
 *      표지–따옴표 간격이 창 안이면 검사되고, 창 밖이면 **경보 목록에 반드시 뜬다.** */
add('ⓠ', '🔴 표지–따옴표 사이에 말이 껴도 창 안이면 검사한다(3건) · 창 밖은 경보 목록에 뜬다', 0,
  () => onSrc('gap'),
  (o) => {
    if (!/검사한 인용 3 건/.test(o)) return '창 안 인용 3건이 검사되지 않았다(조용한 누락)';
    if (!/형태가 아니어서 검사하지 않은 「」 1 건/.test(o)) return '창 밖 인용이 경보 목록에 뜨지 않았다 — 조용히 샜다';
    if (!/판정은 이 차트에서 한다/.test(o)) return '창 밖 인용의 본문이 출력되지 않았다';
    return null;
  });

/* ⓡ 🔴 후보 보존 항등식 — 검사 대상 수가 조용히 줄면 그 자리에서 드러나야 한다. */
add('ⓡ', '🔴 「」 후보 총계 = 검사 + 형태불일치 + 표지없음 (보존 항등식을 출력한다)', 0,
  () => onSrc('gap'),
  (o) => {
    const m = o.match(/「」 후보 총계 (\d+) 건 = 검사 (\d+) \+ 표지형태불일치 (\d+) \+ 표지없음 (\d+)/);
    if (!m) return '보존 항등식이 출력되지 않았다';
    if (Number(m[1]) !== Number(m[2]) + Number(m[3]) + Number(m[4])) return '보존 항등식이 맞지 않는다';
    if (/보존 항등식이 깨졌다/.test(o)) return '게이트 스스로 항등식 파손을 신고했다';
    return null;
  });

/* ⓢ 🔴 잇달아 붙은 `//` 줄에 걸친 인용을 「해석 실패」로 오판하지 않는다.
 *      실물: `wafer.ts:684~686`. 오판하면 게이트 전체가 ERROR(2) 로 멈춘다. */
add('ⓢ', '🔴 연속 `//` 주석에 걸친 「」를 해석 실패로 오판하지 않는다(제품 트리 ERROR 0건)', 0,
  () => run([]),
  (o) => /해석 실패\(ERROR\) 0 건/.test(o) ? null : '연속 // 주석 이음이 깨져 해석 실패가 났다');

/* ⓣ 🔴 R-5 확장 래칫이 **원 래칫과 분리**돼 있다 — 원 기준선을 올리지 않았다는 증거. */
add('ⓣ', '🔴 R-5 확장은 원 기준선(18)을 올리지 않고 별도 기준선으로 래칫한다', 1,
  () => onSrc('lineref', '--r5-ext-baseline', '0'),
  (o) => /확장 기준선 0 건을 넘었다/.test(o) || /R-5 확장 · 원 패턴이 못 잡던 형태 — ❌/.test(o)
    ? null : '확장 래칫이 동작하지 않았다');

/* ⓜ `--json` 경로도 같은 판정을 내는지(소비자가 둘을 섞어 쓴다). */
add('ⓜ', '--json 이 텍스트와 같은 판정·같은 종료코드를 낸다', 1,
  () => onSrc('dead', '--json'),
  (o) => { try { const j = JSON.parse(o); return j.exitCode === 1 && j.summary.FAIL === 1 ? null : 'JSON 판정이 어긋난다'; } catch (e) { return 'JSON 파싱 실패: ' + e.message; } });

let pass = 0;
console.log('check-citations 자체 검증 — 픽스처는 `scripts/fixtures/citations/**`, 대조 정본은 **진짜 03_실습3단계명세.md**\n');
console.log('  ID  기대  실측  판정  설명');
for (const c of CASES) {
  const r = await c.fn();
  const why = r.code === c.expect ? (c.assert ? c.assert(r.out) : null) : `종료코드가 ${c.expect} 가 아니라 ${r.code}`;
  const ok = why === null;
  if (ok) pass++;
  console.log(`  ${c.id}  ${String(c.expect).padEnd(4)}  ${String(r.code).padEnd(4)}  ${ok ? '✅' : '❌'}   ${c.desc}`);
  if (!ok) {
    console.log(`        └ ${why}`);
    console.log(`        └ 출력 발췌: ${r.out.split('\n').filter((l) => /❌|⚠️|폐기 영역|검사한 인용/.test(l)).slice(0, 3).join(' | ').slice(0, 300)}`);
  }
}
console.log(`\n  ${pass}/${CASES.length} 통과`);
if (pass !== CASES.length) {
  console.log('\n❌ 픽스처 실패 — 게이트가 기대대로 동작하지 않습니다.');
  process.exitCode = 1;
} else {
  console.log('\n✅ 픽스처 전건 통과 — 탐지(ⓐⓔⓕⓖ)·오탐없음(ⓑⓒⓓⓗ)·계측기고장 분리(ⓘⓙ)·투명성(ⓚⓛ)이 모두 증명됐습니다.');
}
