/**
 * 텍스처 유닛 번호의 **정본**.
 *
 * ── 왜 이 파일이 있는가 ────────────────────────────────────────────────────
 * `TEX_SUBSTRATE = 0` 이 `scenes/filmGrowth.ts` · `scenes/ionTrajectory.ts` ·
 * `scenes/stepCoverage.ts` **세 곳에서 각자 선언**돼 있었다(check-constants R1).
 * 값이 셋 다 0 이라 아무도 안 봤지만, 정본이 없으면 한쪽만 고쳐도 나머지가 조용히 남는다.
 *
 * 🔴 **재수출로 때우지 않았다.** 세 씬 중 하나를 정본으로 삼고 나머지가 그걸 import 하면
 *    **결합이 거꾸로 생긴다** — 이온 주입 씬이 박막 성장 씬에 의존할 이유가 없는데
 *    「상수를 얻으려고」 서로 남의 씬을 끌어오게 된다. 그래서 어느 씬도 아닌 **제3의 중립 모듈**로 옮겼다.
 *    (같은 저장소가 `AXIS_X` 를 처리한 방식과 같다.)
 *
 * ── 왜 하필 `src/viz/gl/` 인가 ─────────────────────────────────────────────
 * 유닛 번호는 **어느 씬의 것도 아니고** `textures.ts` 의 바인딩 규약에 속한다 —
 * `TextureSet.bind(unit, name)` 에 넘기는 `unit` 과 셰이더 샘플러에 `uniform1i` 로
 * 넣는 번호가 **같아야 한다**는 그 규약이다. 그러니 규약을 정의한 GL 계층,
 * `textures.ts` 바로 옆이 제자리다.
 *
 * `scenes/models/*.model.ts` 에 두지 않은 이유: 그 모듈들은 **씬 하나씩의** 순수
 * 배치·물리 모듈이다. 거기에 넣으면 한 씬의 모델 모듈이 **다른 씬의 바인딩 번호를
 * 소유**하게 되어, 위에서 피한 역방향 결합이 이름만 바꿔 되살아난다.
 *
 * `textures.ts` 안에 넣지 않은 이유: 그 파일은 자산 적재·GPU 객체 수명(네트워크·
 * 컨텍스트 로스트·참조 계수)을 맡는다. 유닛 번호는 의존성이 하나도 없는 순수한
 * 숫자 규약이라 그 무게를 같이 질 필요가 없다.
 *
 * ── 유닛 1·2 는 왜 여기 없는가 (전수 확인 결과) ────────────────────────────
 * `TEX_` 유닛 상수를 저장소 전수로 훑으면 다섯 씬에 흩어져 있다:
 *   · filmGrowth      TEX_SUBSTRATE=0 · TEX_OXIDE=1 · TEX_METAL=2
 *   · stepCoverage    TEX_SUBSTRATE=0 · TEX_FILM=1
 *   · ionTrajectory   TEX_SUBSTRATE=0
 *   · polishProfile   TEX_PAD=0
 *   · plasma          TEX_RESIST=0
 *
 * 이 중 **정본으로 올린 것은 `TEX_SUBSTRATE` 하나뿐**이다. 판단 근거 —
 *
 * ① 겹치기 상수는 씬마다 **차지하는 물질이 다르다.** `TEX_OXIDE=1`(filmGrowth) 과
 *    `TEX_FILM=1`(stepCoverage) 을 한 모듈에 나란히 두면, 둘이 **서로 다른 유닛**인 것처럼
 *    읽히지만 실제로는 **같은 번호 1** 이다. 두 이름을 한 씬이 같이 쓰는 순간 조용히 충돌한다.
 *    공용 모듈은 **정말로 공용인 사실**만 담아야 한다 — 「유닛 0 은 바탕 재질」은 공용이지만
 *    「유닛 1 의 주인」은 공용이 아니다.
 * ② 유닛 1·2 는 각각 **한 파일에서만** 선언된다 — R1(이름 중복)도 R3(값 정본 없음, 0·1·2 는
 *    자명값으로 면제)도 걸리지 않는다. 중복이 아닌 것을 옮기는 것은 이득 없는 범위 확대다.
 *
 * 🟡 `polishProfile.TEX_PAD=0` · `plasma.TEX_RESIST=0` 은 **이름만 다를 뿐 이 파일의
 *    `TEX_SUBSTRATE` 와 같은 자리**(바탕 재질을 유닛 0 에)를 가리킨다. 지금은 각각 한 파일에서만
 *    선언되므로 게이트에 걸리지 않고, 두 파일 모두 이 작업의 배타 범위 밖이라 손대지 않았다.
 *    셋째 씬이 같은 이름을 쓰기 시작하면 그때 R1 로 드러난다 — 그러면 여기로 접으면 된다.
 */

