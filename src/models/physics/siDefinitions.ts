import { siDefinition, type SiDefinition } from '../contract';
import { TEN } from './units';

/**
 * **SI 가 정의로 확정한 상수 — 공정을 가리지 않는 정본. 문헌 계수가 아니다.**
 *
 * 🔴 **왜 이 파일이 생겼나 (2026-08-22 정정).**
 *    아래 두 값이 **자기를 인쇄하지 않은 논문의 S번호**를 달고 있었다:
 *      · `wafer/pointDefect.ts:55`  `withSource(8.617333262e-5, 'eV/K', **'S101'**)`
 *        S101(Sabanskis et al., *Crystals* 11(5) 460)은 본문 §3.2.1 에 **반올림값 8.617×10⁻⁵** 를
 *        적었다. 같은 파일이 그 인쇄값을 `BOLTZMANN_AS_PRINTED` 로 **따로** 두고 있었으므로
 *        **오귀속은 의도가 아니라 누락**이다.
 *      · `etch/wetEtch.ts:143`      `withSource(273.15, 'K', **'S164'**)`
 *        S164(Kleptsyn & Smits, *Sensors and Materials* 14(8))가 진술하는 것은 NaOH·TMAH
 *        아레니우스 계수다. 코드 주석 자신이 「**측정 계수가 아니라 SI 온도눈금 정의**」라고
 *        적어 놓고 그 위에 논문 번호를 달고 있었다.
 *    🔴 저장소가 다른 두 곳에서 이미 같은 진단을 내려 두었는데 이 파일들만 못 따라갔다 —
 *       `packaging/reliability.ts:9`「°C↔K 오프셋은 원장이 **공개 출처로 확정하지 못한 항목**」·
 *       `deposition/diffusion.ts:18`「섭씨→켈빈 변환상수(273.15)는 **어느 원장에도 없다**」.
 *
 * 🔴 **왜 `withSource` 가 아닌가.** `./units.ts` 머리말이 이미 답이다 —
 *    「**단위 환산은 정의이지 측정값이 아니므로 `withSource` 로 감싸면 오히려 거짓 출처가 된다.**」
 *    S번호 원장은 「공개 문헌」 원장이고, **BIPM SI Brochure 도 NIST CODATA 데이터셋도 등재돼
 *    있지 않다**(2026-08-22 원장 2권 전수 확인. NIST 계열은 S212「Faraday 상수 **한 값**」·
 *    S224「NIST/SEMATECH 통계 e-Handbook」·S266「JCGM 106:2012」뿐).
 *
 * 🔴 **왜 `uiGuard` 가 아닌가.** `UI_GUARD_LABEL` = 「출처 없음」의 정의는 **「애초에 뒷받침할
 *    문헌이 존재할 수 없는 값 — 우리가 그은 선」**이다. SI 정의값은 정반대다: 정본이 실재하고
 *    불확도가 0 이다. 또 `UiGuard` 는 스스로 「**계산 경로 계수가 아니라 범위선**」이라 못박았는데
 *    볼츠만은 `exp(−E/kT)` 안에 들어가는 계산 경로 계수다.
 *
 * 🔴 **매직넘버 차단은 면제받지 않는다 — 면제를 요구하지도 않았다.**
 *    `check-sources` 는 `withSource(` 첫 인자만 면제한다(`scripts/check-sources.mjs:203` —
 *    함수명이 정규식에 박혀 있다). 그래서 `siDefinition` 에 새 면제를 달라고 하는 대신,
 *    `./units.ts` 관례 그대로 **허용 리터럴(0·1·2·−1·0.5·100)로만 조립**했다.
 *    **게이트를 넓히지 않고 값을 게이트 안으로 들여놓은 것**이다.
 *
 * 🔴 **조립은 「자릿수를 그대로 읽는」 호너 형식**이다. 옛 십진 표기와 한 자리씩 눈으로 대조되고,
 *    비트 일치는 `tests/unit/si-definitions.test.ts` 가 십진 리터럴과 직접 비교해 못박는다.
 *    (base-100 같은 압축 표기를 쓰면 사람이 검산할 수 없어 오히려 위험해진다.)
 *
 * 🔴 **여기 올릴 것은 「SI 가 정의로 고정한 값」뿐이다.** 측정값·피팅계수는 `withSource`,
 *    우리가 그은 범위선은 `uiGuard`, 순수 십진 접두어 환산은 `./units.ts` 로 간다.
 */

/* 자릿수 조립용 한 자리 수 — 허용 리터럴 0·1·2·−1·0.5·100 만으로 만든다. */
const D3 = 2 + 1;
const D5 = 2 + 2 + 1;
const D6 = 2 + 2 + 2;
const D7 = 2 + 2 + 2 + 1;
const D8 = 2 + 2 + 2 + 2;

/**
 * `8 617 333 262` — 볼츠만 상수(eV/K)의 유효숫자 10자리를 **자릿수 그대로** 호너 형식으로 쌓는다.
 * 왼쪽부터 읽으면 `8·6·1·7·3·3·3·2·6·2` 로 십진 표기 **8.617333262** 와 한 자리씩 대응한다.
 */
const BOLTZMANN_DIGITS =
  ((((((((D8 * TEN + D6) * TEN + 1) * TEN + D7) * TEN + D3) * TEN + D3) * TEN + D3) * TEN + 2) * TEN + D6) * TEN + 2;

/** 10¹⁴ — 위 자릿수를 `8.617333262×10⁻⁵` 로 내리는 소수점 자리. */
const E14 = 100 * 100 * 100 * 100 * 100 * 100 * 100;

/**
 * **볼츠만 상수 k [eV/K] — SI 정의값.**
 *
 * 2019 SI 재정의로 `k = 1.380 649×10⁻²³ J/K` 와 `e = 1.602 176 634×10⁻¹⁹ C` 가 **둘 다 정확값**이
 * 되었으므로 `k/e` 도 정의로 확정된다. 코드가 쓰는 `8.617333262×10⁻⁵` 는 그 몫을
 * **유효숫자 10자리로 끊은 표기**(NIST CODATA 가 게시하는 형태)다.
 *
 * 🔴 **반올림값 `8.617×10⁻⁵` 과 바꿔치면 안 된다.** `wafer/pointDefect.ts` 의 `C^eq` 가
 *    최대 0.137 % 어긋나 원장 허용오차 ±0.1 % 를 깬다(그 파일 주석·골든 테스트가 고정).
 *    반올림값 쪽은 **문헌이 실제로 인쇄한 값**이므로 그쪽은 `withSource` 로 남는다 —
 *    `pointDefect.ts` 의 `BOLTZMANN_AS_PRINTED`(S101) · 후공정 원장 R16 이 확정한
 *    회사 규약값(S54 JESD74A 식[1]). **셋은 서로 다른 개념이므로 통일하지 않는다.**
 */
export const BOLTZMANN_SI_EV_PER_K: SiDefinition = siDefinition(
  BOLTZMANN_DIGITS / E14, 'eV/K',
  'k/e — k = 1.380 649×10⁻²³ J/K · e = 1.602 176 634×10⁻¹⁹ C (2019 SI 재정의로 둘 다 정확값). '
  + '유효숫자 10자리 표기',
);

/**
 * `27 315` — 켈빈 영점의 유효숫자를 자릿수 그대로 쌓는다. `2·7·3·1·5` → **273.15**.
 */
const KELVIN_ZERO_DIGITS = (((2 * TEN + D7) * TEN + D3) * TEN + 1) * TEN + D5;

/**
 * **0 °C = 273.15 K — 섭씨 눈금의 영점 정의.**
 *
 * 섭씨온도는 `t/°C = T/K − 273.15` 로 **정의**된다. 재서 얻은 값이 아니라 눈금의 정의이므로
 * 불확도가 없고, 이 값을 진술하는 것은 실험 논문이 아니라 SI 문서다.
 *
 * 🔴 **켈빈으로 받을 수 있으면 이 상수를 쓰지 마라.** `packaging/reliability.ts` 와
 *    `deposition/diffusion.ts` 는 **호출자에게 켈빈을 요구**해서 환산 자체를 없앴다 — 더 나은 쪽이다.
 *    `etch/wetEtch.ts` 만 원문(S164)이 조건을 °C 로 주기 때문에 환산이 불가피하다.
 */
export const KELVIN_AT_ZERO_CELSIUS: SiDefinition = siDefinition(
  KELVIN_ZERO_DIGITS / 100, 'K',
  '0 °C = 273.15 K — 섭씨 눈금의 영점 정의 (t/°C = T/K − 273.15)',
);
