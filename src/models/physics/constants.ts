/**
 * **공정을 가리지 않는 문헌 상수 — 정본.**
 *
 * 이 디렉터리의 상수 정본은 **성격에 따라 셋으로 갈린다.** 새 상수를 놓을 때 여기부터 고른다:
 *   · `./units.ts`         — 십진 접두어 환산(1 min = 60 s). 정의이고 출처가 없다.
 *   · `./siDefinitions.ts` — SI 가 **정의로 고정**한 값(볼츠만 k, 켈빈 영점). 정의이고 출처가 없다.
 *   · **여기(`./constants.ts`)** — **문헌이 인쇄한 값** 중 **두 공정 이상이 함께 쓰는 것.**
 *     S번호가 붙고 `withSource` 로 감싼다.
 *   · 한 공정만 쓰는 문헌 상수는 **그 공정 파일 곁에** 둔다. 여기 올리지 않는다.
 *
 * 🔴 **왜 생겼나 (2026-08-22).** `BOLTZMANN_EV_PER_K` 가 **4개 파일에서 각자 선언**되고 있었다
 *    (`deposition/cvd.ts` · `deposition/diffusion.ts` · `etch/wetEtch.ts` · `packaging/reliability.ts`).
 *    거기에 `metal/electromigration.ts` 가 `EM_` 접두만 붙여 **같은 값을 다섯 번째로** 선언했다.
 *    🔴 **`check-constants` 가 이걸 오래 못 잡은 이유가 특이하다** — 같은 이름의 여섯 번째 선언인
 *    `wafer/pointDefect.ts` 가 **다른 값**(SI 정의값)을 갖고 있어서 판정이 **R2(정본 갈림)** 로
 *    분류됐고, R2 에는 「통일하면 골든이 깨진다」는 **의도된 면제**가 등재돼 있었다.
 *    R1 과 R2 는 배타적이라(`scripts/check-constants.mjs:210`) **R2 면제가 R1 위반을 통째로 덮었다.**
 *    면제는 「**값이 두 갈래인 것**」만 봐주려 한 것이지 「**같은 값을 네 번 선언하는 것**」을
 *    봐주려던 것이 아니다. pointDefect 의 값이 `siDefinitions` 로 빠지자 가려져 있던 R1 이 드러났다.
 *
 * 🔴 **통일 판정 — 볼츠만은 「개념 셋」이고 통일 범위는 그중 하나뿐이다.**
 *    ① **SI 정의값** `8.617333262e-5` — `./siDefinitions.ts`. 출처 없음(정의).
 *    ② **원논문 인쇄값** `8.617e-5` (S101) — `wafer/pointDefect.ts` 의 `BOLTZMANN_AS_PRINTED`.
 *       재현 실패를 **증명하는 용도**라 값이 ③과 같아도 **주인이 다르다. 합치지 않는다.**
 *    ③ **회사 규약값** `8.617e-5` (S54 JESD74A 식[1] · 후공정 원장 R16 · 허용오차 ±0.5 %)
 *       — **아래 하나로 합친 것이 이것이다.** 다섯 곳이 전부 같은 문장을 주석에 적고 있었다.
 *    ①②③ 은 서로 다른 개념이므로 **통일하지 않는다.** ③ 안에서만 정본을 하나로 모았다.
 */

