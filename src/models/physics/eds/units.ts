/**
 * P7 EDS — **mil ↔ µm 환산의 정본.** 문헌 계수가 아니라 **정의**다.
 *
 * ════════════════════════════════════════════════════════════════════════════
 * 🔴 왜 `withSource(…, 'S229')` 로 감싸지 않는가
 * ════════════════════════════════════════════════════════════════════════════
 * `1 mil = 25.4 µm` 는 **1959 국제 야드·파운드 협정**이 확정한 국제 인치 정의
 * (`1 in ≡ 25.4 mm` 정확값)에서 곧바로 나온다. 잰 값이 아니라 **눈금의 정의**이며 불확도가 0 이다.
 * `../units.ts` 머리말이 이미 이 원칙을 못박아 두었다 —
 *   「**단위 환산은 정의이지 측정값이 아니므로 `withSource` 로 감싸면 오히려 거짓 출처가 된다.**」
 * S229(Tektronix, *Probe Card Tutorial*)는 **프로브 실무 범위**를 진술하는 문헌이지
 * 인치를 정의하는 문서가 아니다. 여기에 S229 를 달면 원장이 하지 않은 말을 하게 된다.
 *
 * 🔴 **그래서 매직넘버 차단을 면제받지 않는다 — 면제를 요구하지도 않았다.**
 *    `check-sources` 의 허용 리터럴(0 · 1 · 2 · −1 · 0.5 · 100)만으로 조립한다.
 *    조립은 `../siDefinitions.ts` 가 쓴 것과 같은 **호너 자릿수 형식**이라 십진 표기와
 *    한 자리씩 눈으로 대조된다(`2 · 5 · 4` → **25.4**). 비트 일치는
 *    `tests/unit/eds-mil-conversion.test.ts` 가 십진 리터럴과 직접 비교해 못박는다.
 *
 * ════════════════════════════════════════════════════════════════════════════
 * 🔴 왜 이 파일인가 — 세 후보를 비교한 결과다 (DEV 판정 2026-08-22)
 * ════════════════════════════════════════════════════════════════════════════
 *  ① `physics/units.ts`  — 스스로 「**두 공정 이상이 실제로 쓰는 것**만」이라고 못박았고,
 *     「**공정 전용 환산은 그 공정 곁에 둔다**(`physics/metal/units.ts` 처럼)」고 선례까지 적어 두었다.
 *     mil 은 **EDS 프로브 카드에서만** 쓰인다(저장소 전수: `physics/eds/**` · `labs/eds.ts` 뿐).
 *     → 올리면 그 파일이 스스로 세운 규칙을 첫 항목부터 어긴다. **탈락.**
 *  ② `physics/siDefinitions.ts` — 스스로 「**SI 가 정의로 고정한 값**만」이라고 못박았다.
 *     국제 인치는 SI 단위가 아니라 **야드·파운드계와 SI 를 잇는 협정값**이고, `siDefinition()`
 *     이 요구하는 「SI 정의 관계식」을 적을 수 없다. → **탈락.**
 *  ③ **이 파일** — `physics/metal/units.ts`(P6 전용 환산)와 같은 층·같은 형식이다. **채택.**
 *
 * 🔴 **두 공정 이상이 mil 을 쓰게 되면 그때 `../units.ts` 로 올린다.** 그전에 올리면
 *    「둘 이상이 쓰는 것만」이라는 그 파일의 판정 기준이 무의미해진다.
 *
 * 🔴 `tests/golden/packaging.golden.test.ts` 의 `MM2_PER_IN2 = 25.4 * 25.4` 는 **중복 선언이 아니다.**
 *    `check-constants` 의 스캔 뿌리는 `src/**` 와 `scripts/**` 둘뿐이고(`scripts/check-constants.mjs`
 *    의 `SCAN`) `tests/**` 는 들어 있지 않다. 그 파일 주석이 스스로 「시험 설정이므로 테스트가
 *    소유한다」고 선언한 그대로다. 제품 코드 안에서 25.4 를 선언하는 곳은 **여기 하나**다.
 */
