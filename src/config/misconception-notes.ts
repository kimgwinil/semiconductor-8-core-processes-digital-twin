/**
 * 🔴 **「오해 교정」 note 블록 표시 스위치.** 표시만 끈다 — 원고는 하나도 고치지 않는다.
 *
 * // CEO 지시 2026-08-24 로 비활성. 화면 표시만 비활성. 원고(`src/content/ko/*.json`)는 보존.
 * // 🔴 되살리는 법: `SHOW_MISCONCEPTION_NOTES` 를 `true` 로 되돌린다. 그 한 줄뿐이다.
 *
 * ── 무엇을 끄는가 ──────────────────────────────────────────────────
 * 학습자의 **오개념을 미리 교정하는** `note` 블록. CEO 인용 예:
 *   「자유공 볼이 구슬 모양 그대로 패드 위에 얹힌 그림을 정상으로 오해하기 쉽다 …」
 *
 * ── 무엇을 남기는가 (⛔ 지우지 마라) ────────────────────────────────
 *  🟢 공정이 무엇이고 어떻게 돌아가는가를 설명하는 본문 — `p`·`h`·`list`·`table`·`formula`
 *  🟢 도해 범위 안내(「이 단면에는 나오지 않는다」)·실습 조작 안내 — `note` 라도 남긴다
 *  🟢 한계선 초과 안내 등 제품 동작 설명
 *
 * 🔴 **`note` 를 통째로 끄지 않는다.** 실측 45건 중 오해 교정은 32건이고,
 *    나머지 13건(본문 설명 4 · 도해범위/실습안내 7 · 애매 2)은 **학습자에게 하는 말**이라 남긴다.
 *    그래서 타입이 아니라 **문면**으로 가른다.
 */
export const SHOW_MISCONCEPTION_NOTES = false;

/**
 * 오해 교정임을 드러내는 단서. **강한 것만 넣는다** — 「…이 아니다」처럼 흔한 부정문을
 * 넣으면 도해 범위 안내(「부품이 아니다」)와 공정 설명(「쌓이는 것이 아니라 자란다」)까지
 * 함께 걸려서, 남겨야 할 교육 내용이 사라진다.
 */
const CUES: readonly RegExp[] = [
  /오해(?:하기 쉽|다|가 아니|입니다)/,
  /흔한 오해|흔한 오판|잦은 오답|흔한 실수|가장 흔한/,
  /착각|혼동/,
  /(?:외우|생각하|떠올리|보이|읽|기억하)기 쉽/,
  /기억하면 (?:핵심|헷갈)/,
  /뒤집어 외우/,
  /정확하지 않다|틀렸다|반대다/,
  /도해(?:에서|의|를|가)?[^.]{0,30}(?:오해|아니|읽지)/,
];

/** 이 `note` 문면이 「오해 교정」인가. */
export function isMisconceptionNote(text: string): boolean {
  return CUES.some((re) => re.test(text));
}
